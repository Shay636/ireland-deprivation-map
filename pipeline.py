# ── Step 9: Summary stats ─────────────────────────────────────────────────────

def build_summary(gdf, dublin_df):
    print("[9] Building summary statistics...")

    county_col = "COUNTY_ENGLISH"
    county_df = (
        gdf.groupby(county_col, dropna=False)
        .agg(
            total_sas        = ("SA_GUID_2022", "count"),
            underserved_sas  = ("underserved", "sum"),
            very_deprived_sas= ("very_deprived", "sum"),
            total_pop        = ("pop", "sum"),
            avg_dep_score    = ("dep_score", "mean"),
        )
        .reset_index()
        .rename(columns={county_col: "county"})
    )

    # Underserved population: sum pop where underserved=True per county
    us_pop = (
        gdf[gdf["underserved"]]
        .groupby(county_col, dropna=False)["pop"]
        .sum()
        .rename("underserved_pop")
    )
    county_df = county_df.merge(us_pop, left_on="county", right_index=True, how="left")
    county_df["underserved_pop"] = county_df["underserved_pop"].fillna(0)
    county_df["pct_underserved_sas"] = (
        100 * county_df["underserved_sas"] / county_df["total_sas"]
    ).round(1)
    county_df = county_df.sort_values("underserved_pop", ascending=False)

    out = os.path.join(OUTPUTS, "summary.csv")
    county_df.to_csv(out, index=False)
    print(f"  County summary → {out}")

    if not dublin_df.empty:
        dub_out = os.path.join(OUTPUTS, "dublin_lea_breakdown.csv")
        dublin_df.to_csv(dub_out, index=False)
        print(f"  Dublin LEA breakdown → {dub_out}")

    total_pop = gdf.loc[gdf["pop"].notna(), "pop"].sum()
    under_pop = gdf.loc[gdf["underserved"] & gdf["pop"].notna(), "pop"].sum()
    total_sa  = len(gdf)
    print(f"\n  ── National Summary ─────────────────────────────")
    print(f"  Small Areas analysed:           {total_sa:,}")
    print(f"  Total population:               {int(total_pop):,}")
    print(f"  Underserved SAs:                {int(gdf['underserved'].sum()):,}  "
          f"({100*gdf['underserved'].sum()/total_sa:.1f}%)")
    print(f"  Population in underserved SAs:  {int(under_pop):,}  "
          f"({100*under_pop/total_pop:.1f}%)")
