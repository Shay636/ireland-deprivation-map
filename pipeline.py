# ── Step 2: SAPS — build deprivation composite ────────────────────────────────

def load_saps():
    dest = os.path.join(CACHE, "saps_2022_sa.csv")
    download_file(SAPS_URL, dest, "CSO SAPS 2022 (Small Area)")

    print("  Reading SAPS (this may take a moment — 40 MB, 795 columns)...")
    # Read only the columns we need
    useful_cols = [
        "GUID", "GEOGID",
        # Population
        "T1_1AGETT",
        # Employment (T8_1)
        "T8_1_STUT", "T8_1_LTUT",           # unemployed
        "T8_1_WT",                            # at work
        "T8_1_TT",                            # total econ active+inactive
        # Social class (T9_1)
        "T9_1_SST", "T9_1_UST", "T9_1_TT",  # semi-skilled, unskilled, total
        # Education (T10_1): age left school
        "T10_1_LT15T", "T10_1_15T", "T10_1_TT",
        # Housing tenure (T6_3)
        "T6_3_RLAH",   # LA renting (households)
        "T6_3_RPLH",   # Private renting
        "T6_3_OMLH",   # Owner with mortgage
        "T6_3_OOH",    # Owner outright
        "T6_3_TH",     # Total households
        # Overcrowding (T6_8)
        "T6_8_OVD",    # Overcrowded
        "T6_8_T",      # Total
    ]

    df = pd.read_csv(dest, usecols=useful_cols, low_memory=False)
    n = len(df)
    print(f"  Loaded {n} Small Areas.")

    # ── Build rates ────────────────────────────────────────────────────────────
    def safe_rate(num, denom):
        d = pd.to_numeric(denom, errors="coerce").replace(0, np.nan)
        n_ = pd.to_numeric(num, errors="coerce")
        return (n_ / d * 100).clip(0, 100)

    df["unemp_rate"]    = safe_rate(df["T8_1_STUT"] + df["T8_1_LTUT"], df["T8_1_TT"])
    df["la_rent_rate"]  = safe_rate(df["T6_3_RLAH"], df["T6_3_TH"])
    df["prv_rent_rate"] = safe_rate(df["T6_3_RPLH"], df["T6_3_TH"])
    df["owner_rate"]    = safe_rate(df["T6_3_OMLH"] + df["T6_3_OOH"], df["T6_3_TH"])
    df["low_class_rate"]= safe_rate(df["T9_1_SST"]  + df["T9_1_UST"], df["T9_1_TT"])
    df["low_edu_rate"]  = safe_rate(df["T10_1_LT15T"] + df["T10_1_15T"], df["T10_1_TT"])
    df["overcrowd_rate"]= safe_rate(df["T6_8_OVD"], df["T6_8_T"])
    df["pop"]           = pd.to_numeric(df["T1_1AGETT"], errors="coerce")

    # ── Standardise and compose ────────────────────────────────────────────────
    indicators = {
        "unemp_rate":     +1,   # higher → more deprived
        "la_rent_rate":   +1,
        "prv_rent_rate":  +1,
        "low_class_rate": +1,
        "low_edu_rate":   +1,
        "overcrowd_rate": +1,
        "owner_rate":     -1,   # higher → less deprived
    }

    raw = np.zeros(n)
    for col, sign in indicators.items():
        vals = df[col].values.astype(float)
        # z-score ignoring NaN
        z = (vals - np.nanmean(vals)) / (np.nanstd(vals) + 1e-9)
        z = np.where(np.isfinite(z), z, 0.0)
        raw += sign * z

    # Negate so more negative = more deprived (Pobal sign convention)
    df["dep_score"] = -raw

    # Scale to approx Pobal range (observed −45 to +30) via percentile stretch
    p2, p98 = np.nanpercentile(df["dep_score"], [2, 98])
    df["dep_score"] = (df["dep_score"] - np.nanmean(df["dep_score"])) / (
        np.nanstd(df["dep_score"]) + 1e-9
    ) * 7.0  # ≈ scales so ±2σ → ±14, matching Pobal spread

    print(f"  Deprivation score range: "
          f"{df['dep_score'].min():.1f} to {df['dep_score'].max():.1f}")

    # "Very deprived" ≈ below −10 in Pobal; here use the equivalent bottom 5 %ile
    p5 = df["dep_score"].quantile(0.05)
    df["very_deprived_flag"] = df["dep_score"] < p5
    print(f"  Very deprived threshold (P5): {p5:.2f}  "
          f"({df['very_deprived_flag'].sum()} SAs)")

    return df[["GUID", "GEOGID", "pop", "dep_score", "very_deprived_flag"]]


# ── Step 3: SA Boundaries ─────────────────────────────────────────────────────

def load_boundaries():
    dest = os.path.join(CACHE, "sa_boundaries_2022_gen20m.geojson")
    if not os.path.exists(dest):
        ok = download_file(SA_GEOJSON_URL, dest, "SA Boundaries 2022 Generalised 20m")
        if not ok:
            fetch_sa_boundaries_via_featureserver(dest)

    print("  Reading GeoJSON into GeoDataFrame...")
    gdf = gpd.read_file(dest)
    if gdf.crs and gdf.crs.to_epsg() != 4326:
        gdf = gdf.to_crs(epsg=4326)

    # Normalise the join key column name
    # GeoJSON from ArcGIS uses the field names from the FeatureServer query
    if "SA_GUID_2022" not in gdf.columns and "properties" in dir(gdf):
        raise KeyError("SA_GUID_2022 column missing from boundaries GeoDataFrame")

    print(f"[3] Loaded {len(gdf)} SA polygons. "
          f"Columns: {[c for c in gdf.columns if c != 'geometry']}")
    return gdf


# ── Step 4: Join ──────────────────────────────────────────────────────────────

def join_data(gdf, saps):
    # Primary join: SA_GUID_2022 (boundary) = GUID (SAPS)
    merged = gdf.merge(saps, left_on="SA_GUID_2022", right_on="GUID", how="left")
    missing = merged["dep_score"].isna().sum()
    if missing:
        # Fallback: SA_PUB2022 (boundary) = GEOGID (SAPS)
        fallback = saps.set_index("GEOGID")[["dep_score","pop","very_deprived_flag"]]
        no_match_mask = merged["dep_score"].isna()
        for idx, row in merged[no_match_mask].iterrows():
            pub = row.get("SA_PUB2022", "")
            if pub in fallback.index:
                merged.at[idx, "dep_score"]          = fallback.at[pub, "dep_score"]
                merged.at[idx, "pop"]                = fallback.at[pub, "pop"]
                merged.at[idx, "very_deprived_flag"] = fallback.at[pub, "very_deprived_flag"]
        remaining = merged["dep_score"].isna().sum()
        print(f"  After fallback join: {remaining} SAs still unmatched "
              f"(composite/new SAs, expected).")
    else:
        print(f"  All SAs matched on GUID.")

    print(f"[4] Joined data. Rows: {len(merged)}, "
          f"matched: {merged['dep_score'].notna().sum()}")
    return merged


# ── Step 5: Distance to nearest service ───────────────────────────────────────

def calc_distances(gdf, services):
    print("[5] Calculating distances to nearest addiction service...")
    centroids = gdf.geometry.centroid
    clat = centroids.y.values
    clon = centroids.x.values
    slat = services["lat"].values
    slon = services["lng"].values

    n = len(clat)
    min_dist    = np.full(n, np.inf)
    nearest_name = np.empty(n, dtype=object)

    for i in range(n):
        if not np.isfinite(clat[i]) or not np.isfinite(clon[i]):
            min_dist[i] = np.nan
            nearest_name[i] = ""
            continue
        dists = haversine_matrix(clat[i], clon[i], slat, slon)
        idx = int(np.argmin(dists))
        min_dist[i]     = dists[idx]
        nearest_name[i] = services.iloc[idx]["name"]

    gdf = gdf.copy()
    gdf["dist_km"]        = min_dist
    gdf["nearest_service"] = nearest_name
    valid = np.isfinite(min_dist)
    print(f"  Distance range: {min_dist[valid].min():.1f} – {min_dist[valid].max():.1f} km")
    return gdf


# ── Step 6: Flag underserved areas ────────────────────────────────────────────

def flag_underserved(gdf):
    valid = gdf["dep_score"].notna() & gdf["dist_km"].notna()
    scores = gdf.loc[valid, "dep_score"]
    dists  = gdf.loc[valid, "dist_km"]

    dep_threshold  = scores.quantile(0.25)
    dist_threshold = dists.quantile(0.75)

    gdf["high_deprivation"] = gdf["dep_score"] <= dep_threshold
    gdf["far_from_service"] = gdf["dist_km"]  >= dist_threshold
    gdf["underserved"]      = gdf["high_deprivation"] & gdf["far_from_service"]
    gdf["very_deprived"]    = gdf.get("very_deprived_flag", False)

    n_us  = gdf["underserved"].sum()
    n_vd  = gdf["very_deprived"].sum()
    total = len(gdf)
    print(f"[6] Deprivation threshold (Q25): {dep_threshold:.2f}")
    print(f"    Distance threshold  (Q75):  {dist_threshold:.2f} km")
    print(f"    Underserved SAs: {n_us} ({100*n_us/total:.1f}%)")
    print(f"    Very deprived SAs (P5): {n_vd} ({100*n_vd/total:.1f}%)")
    return gdf, dep_threshold, dist_threshold


# ── Step 7: Dublin breakdown ──────────────────────────────────────────────────

def dublin_breakdown(gdf):
    dublin = gdf[gdf["COUNTY_ENGLISH"].str.upper().str.contains("DUBLIN", na=False)].copy()
    if dublin.empty:
        print("[7] No Dublin SAs found.")
        return pd.DataFrame()
    summary = (
        dublin.groupby("CSO_LEA")
        .agg(
            total_sas   = ("SA_GUID_2022", "count"),
            underserved = ("underserved", "sum"),
            pop         = ("pop", "sum"),
        )
        .reset_index()
        .sort_values("underserved", ascending=False)
    )
    print(f"[7] Dublin breakdown across {len(summary)} Local Electoral Areas.")
    return summary


# ── Step 8: Map ───────────────────────────────────────────────────────────────

def _dep_colour(score, s_min, s_max):
    if pd.isna(score):
        return "#aaaaaa"
    t = max(0.0, min(1.0, (score - s_min) / max(s_max - s_min, 1e-9)))
    if t < 0.5:
        r = int(200 + (1 - 2*t) * 55)
        g = int(30  + 2*t * 100)
        b = int(30  + 2*t * 50)
    else:
        r = int(200 - (2*t - 1) * 160)
        g = int(130 + (2*t - 1) * 95)
        b = int(80  + (2*t - 1) * 130)
    return f"#{r:02x}{g:02x}{b:02x}"


