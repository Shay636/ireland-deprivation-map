"""
Ireland Addiction Treatment Access vs Deprivation Analysis — Small Area Edition
===============================================================================
Uses CSO Census 2022 Small Area Population Statistics (SAPS) to build a
custom deprivation composite at Small Area level (~18,500 SAs, 5× finer than
the previous ED-level analysis) joined to CSO 2022 SA boundaries (generalised 20m).

Deprivation composite (custom, SAPS-derived) components — all standardised:
  + unemployment rate (short-term + long-term / economically active)
  + LA renting rate
  + private renting rate
  + low social class rate (unskilled + semi-skilled)
  + low education rate (left school ≤ 15)
  + overcrowding rate
  − owner-occupation rate  (negative = affluent indicator)
Result negated so more negative = more deprived (Pobal sign convention).

Join: SAPS.GUID → SA_boundary.SA_GUID_2022
"""

