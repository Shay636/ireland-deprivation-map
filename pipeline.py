# ── Helpers ───────────────────────────────────────────────────────────────────

def download_file(url, dest, desc=""):
    if os.path.exists(dest):
        print(f"  Cached: {dest}")
        return True
    print(f"  Downloading {desc or url[:80]}...")
    req = urllib.request.Request(url, headers={"User-Agent": "IrelandResearch/1.0"})
    try:
        with urllib.request.urlopen(req, timeout=180) as resp:
            data = resp.read()
        # Detect if the response is a "pending" JSON from the ArcGIS download service
        if b'"status":"Pending"' in data[:200] or b'"status": "Pending"' in data[:200]:
            print("  Download is still being generated by ArcGIS — will use FeatureServer instead.")
            return False
        with open(dest, "wb") as f:
            f.write(data)
        print(f"  Saved {len(data)/1_000_000:.1f} MB → {dest}")
        return True
    except Exception as e:
        print(f"  Download failed: {e}")
        return False


def fetch_sa_boundaries_via_featureserver(dest):
    """Page through ArcGIS FeatureServer to assemble SA boundaries GeoJSON."""
    print("  Fetching SA boundaries via ArcGIS FeatureServer (paging)...")
    features = []
    offset = 0
    batch = 2000
    fields_out = (
        "SA_GUID_2022,SA_PUB2022,SA_GEOGID_2022,COUNTY_ENGLISH,"
        "COUNTY_GAEILGE,CSO_LEA,ED_ID_STR,ED_ENGLISH"
    )
    while True:
        url = (
            f"{SA_FEATURESERVER}/query?"
            f"where=1%3D1&outFields={urllib.parse.quote(fields_out)}"
            f"&resultOffset={offset}&resultRecordCount={batch}"
            f"&returnGeometry=true&geometryPrecision=5&outSR=4326&f=geojson"
        )
        req = urllib.request.Request(url, headers={"User-Agent": "IrelandResearch/1.0"})
        with urllib.request.urlopen(req, timeout=60) as resp:
            chunk = json.loads(resp.read())
        batch_feats = chunk.get("features", [])
        features.extend(batch_feats)
        print(f"    ...fetched {len(features)} SAs so far")
        if len(batch_feats) < batch:
            break
        offset += batch

    geojson = {
        "type": "FeatureCollection",
        "features": features,
    }
    with open(dest, "w") as f:
        json.dump(geojson, f)
    print(f"  Saved {len(features)} SA features → {dest}")


def haversine_matrix(lat1, lon1, lat2_arr, lon2_arr):
    R = 6371.0
    lat1, lon1 = math.radians(lat1), math.radians(lon1)
    lat2 = np.radians(lat2_arr)
    lon2 = np.radians(lon2_arr)
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = np.sin(dlat / 2)**2 + math.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2)**2
    return R * 2 * np.arcsin(np.sqrt(a))


